def generate_pipeline_code(
    source_label: str,
    target_col: str,
    task_type: str,
    best_model_key: str,
    model_label: str,
    best_params: dict | None = None
) -> str:
    """Generate a readable, standalone Python script string."""

    params = best_params or {}
    params_str = ", ".join(f"{k}={repr(v)}" for k, v in params.items())
    if params_str:
        params_str = ", " + params_str

    # ── Define model imports and instantiation ─────────────────────────────────
    model_imports = {
        "logreg": f"from sklearn.linear_model import LogisticRegression\nmodel = LogisticRegression(max_iter=1000, random_state=42{params_str})",
        "rf": ("from sklearn.ensemble import RandomForestClassifier" if task_type == "classification" else "from sklearn.ensemble import RandomForestRegressor") + f"\nmodel = {'RandomForestClassifier' if task_type == 'classification' else 'RandomForestRegressor'}(random_state=42{params_str if params_str else ', n_estimators=100'})",
        "xgb": ("from xgboost import XGBClassifier" if task_type == "classification" else "from xgboost import XGBRegressor") + f"\nmodel = {'XGBClassifier' if task_type == 'classification' else 'XGBRegressor'}(random_state=42{params_str if params_str else ', n_estimators=100'})",
        "lgbm": ("from lightgbm import LGBMClassifier" if task_type == "classification" else "from lightgbm import LGBMRegressor") + f"\nmodel = {'LGBMClassifier' if task_type == 'classification' else 'LGBMRegressor'}(random_state=42{params_str if params_str else ', n_estimators=100'})",
        "linreg": f"from sklearn.linear_model import LinearRegression\nmodel = LinearRegression({params_str.lstrip(', ')})"
    }

    model_setup = model_imports.get(best_model_key, "# Model not found, please configure manually.")

    # ── Template ─────────────────────────────────────────────────────────────
    template = f"""\"\"\"
Generated by Data Intelligence Assistant (DIA)
Reproducing the best model ({model_label}) for target: '{target_col}'
\"\"\"

import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import RobustScaler, TargetEncoder, OneHotEncoder, LabelEncoder

# 1. Load Data
# (Update this path to match your actual data source: {source_label})
df = pd.read_csv("your_dataset.csv")

# 2. Clean Data
target_col = "{target_col}"
df = df.dropna(subset=[target_col])

# Drop near-constant columns and high-cardinality strings
feature_cols = [
    c for c in df.columns
    if c != target_col
    and df[c].nunique() > 1
    and not (df[c].dtype == object and df[c].nunique() / len(df) > 0.5)
]

X = df[feature_cols]
y_raw = df[target_col]

# 3. Prepare Target
"""

    if task_type == "classification":
        template += """le = LabelEncoder()
y = le.fit_transform(y_raw.astype(str))
"""
    else:
        template += """y = pd.to_numeric(y_raw, errors="coerce")
valid_mask = ~pd.isna(y)
X = X[valid_mask]
y = y[valid_mask].values
"""

    template += f"""
# 4. Split Data
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42{", stratify=y" if task_type == "classification" else ""}
)

# 5. Build Preprocessor
numeric_cols = X_train.select_dtypes(include=["number"]).columns.tolist()
cat_cols_all = X_train.select_dtypes(include=["object", "category"]).columns.tolist()

low_card_cols = [c for c in cat_cols_all if X_train[c].nunique() < 10]
high_card_cols = [c for c in cat_cols_all if X_train[c].nunique() >= 10]

numeric_pipe = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", RobustScaler()),
])
low_card_pipe = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
])
high_card_pipe = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", TargetEncoder(target_type="auto", cv=5)),
])

transformers = []
if numeric_cols:
    transformers.append(("num", numeric_pipe, numeric_cols))
if low_card_cols:
    transformers.append(("cat_low", low_card_pipe, low_card_cols))
if high_card_cols:
    transformers.append(("cat_high", high_card_pipe, high_card_cols))

preprocessor = ColumnTransformer(transformers=transformers, remainder="drop")

# 6. Initialize Model
{model_setup}

# 7. Create Full Pipeline & Train
pipeline = Pipeline([
    ("preprocessor", preprocessor),
    ("model", model)
])

print("Training model...")
pipeline.fit(X_train, y_train)

# 8. Evaluate
score = pipeline.score(X_test, y_test)
print(f"Test Score ({'Accuracy' if task_type == 'classification' else 'R²'}): {{score:.4f}}")
"""

    return template

